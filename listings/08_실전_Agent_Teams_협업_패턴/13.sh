CRITICAL BUG: 사용자들이 첫 메시지를 보낸 직후 채팅 앱의 연결이 끊긴다고 보고했다. 근본 원인을 시급히 찾아야 한다.
5명의 조사관으로 구성된 에이전트 팀을 생성한다. 각 조사관은 하나의 가설을 깊이 있게 조사해야 한다. 이들은 과학자들이 동료 심사(Peer Review)를 하듯이 서로의 이론이 틀렸음을 입증하려고 노력해야 한다.
INVESTIGATOR 1 - WebSocket 가설:
"버그는 우리의 WebSocket 구현에 있다"
조사 내용:
- WebSocket 연결 라이프사이클 (open, message, close 이벤트)
- send() 호출 후 조기 close() 호출이 있는지 확인
- 하트비트/핑-퐁 구현 검토
- 재연결 로직 확인
증거 수집: 연결 로그, 이벤트 시퀀스, 종료 코드
INVESTIGATOR 2 - 인증 가설:
"버그는 인증/세션과 관련되어 있다"
조사 내용:
- 토큰 갱신 로직의 타이밍
- 세션 타임아웃 설정
- 클라이언트와 서버 간의 인증 상태 동기화
- 메시지 전송 시 토큰 유효성 검사
증거 수집: 인증 로그, 토큰 만료 시간, 세션 상태
INVESTIGATOR 3 - 서버 인프라 가설:
"버그는 서버/인프라 설정에 있다"
조사 내용:
- Nginx/로드 밸런서 프록시 타임아웃 설정
- WebSocket 업그레이드 처리
- 연결 풀(Connection Pool) 제한
- 서버 리소스 고갈
증거 수집: 서버 설정 파일, 로드 밸런서 로그, 연결 메트릭
INVESTIGATOR 4 - 클라이언트 메모리 가설:
"버그는 클라이언트 측 메모리/리소스 문제이다"
조사 내용:
- 이벤트 리스너 누적
- 클로저(Closure) 메모리 누수
- 대용량 객체 보유
- 가비지 컬렉션 패턴
증거 수집: 힙 스냅샷, 메모리 프로파일, 이벤트 리스너 개수
INVESTIGATOR 5 - 레이스 컨디션 가설:
"버그는 비동기 코드의 타이밍/레이스 컨디션이다"
조사 내용:
- 메시지 전송에서의 Async/await 패턴
- 처리되지 않은 프로미스 거부 (Unhandled Promise Rejections)
- 네트워크 작업 중 상태 업데이트
- 이벤트 순서 가정
증거 수집: 콘솔 오류, 비동기 스택 트레이스, 상태 전환 로그
토론 규칙:
1. 각 조사관은 초기 증거를 제시한다 (15분).
2. 다른 조사관들은 "당신의 증거로는 X를 설명할 수 없다"와 같이 이의를 제기한다.
3. 이의를 제기받은 조사관은 반박하거나 인정해야 한다.
4. 하나의 가설이 명확하고 충분한 근거를 확보할 때까지 토론을 계속한다.
5. 토론 과정을 /debug/investigation-log.md에 문서화한다.
