인증 모듈을 검토할 에이전트 팀을 구성해줘.
이 기능은 보안과 코드 품질에 매우 중요한 부분이므로, 다음 두 명의 전문 리뷰어를 생성한다:
REVIEWER 1 - 보안 리뷰어 (Security Reviewer):
당신의 유일한 목표는 보안이다. 침투 테스터(penetration tester)라고 가정하고 코드를 무너뜨리려고 시도한다.
검토 항목:
- 비밀번호 해싱: bcrypt나 Argon2 알고리즘이 올바르게 적용되었는지 확인.
- 세션 보안: 세션 토큰의 엔트로피가 충분한지(최소 128비트), HttpOnly 및 Secure 플래그가 설정되었는지 검증.
- 취약점 분석: 비교 로직에서 타이밍 공격(Timing Attack) 가능성이 있는지 확인.
- 방어 기제: 로그인 시도 횟수 제한(Rate Limiting)이 구현되었는지 점검.
발견된 각 문제에 대해 다음을 제공한다:
- 위험도 (Critical/High/Medium/Low)
- 정확한 파일:줄 위치 (가능한 경우)
- 공격 시나리오 시연 (간략하게)
- 권장 수정 사항
산출물: 위험도 등급을 포함하여 /reviews/auth-security.md에 작성.
REVIEWER 2 - 코드 품질 리뷰어 (Quality Reviewer):
당신의 유일한 목표는 코드 품질, 유지 보수성 및 에러 처리이다. 최종 품질 검사를 수행하는 시니어 개발자라고 가정한다.
검토 항목:
- 복잡도 측정: 함수당 순환 복잡도(Cyclomatic Complexity)가 10을 넘지 않는지 확인.
- 예외 처리: 에러 핸들링이 누락된 비동기 로직이 있는지 전수 조사 (처리되지 않은 프로미스 거부).
- 개인정보: 로그 출력 시 민감한 정보(비밀번호, 이메일 등)가 유출되지 않는지 점검 (민감 데이터 로깅).
- 일관성: 프로젝트의 명명 규칙(Naming Convention)을 준수하는지 확인.
발견된 각 문제에 대해 다음을 제공한다:
- 영향 (예: 유지 보수 비용, 프로덕션 위험)
- 정확한 파일:줄 위치 (가능한 경우)
- 리팩터링 제안 (구체적인 코드 예시)
산출물: 리팩터링 제안을 포함하여 /reviews/auth-quality.md에 작성.
협력 규칙:
- 각 리뷰어는 먼저 독립적으로 작업한다 (20분).
- 이후 팀 메일박스를 통해 서로의 발견 사항을 공유하고 토론한다.
- 한 리뷰어의 발견 사항이 다른 리뷰어의 영역에 영향을 미치는 경우, 토론한다.
- 토론 후, 주요 발견 사항과 다음 단계를 요약하는 통합 보고서를 /reviews/auth-consolidated-review.md에 작성한다.
