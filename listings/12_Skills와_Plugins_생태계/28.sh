# DB Migration Assistant
필요한 도구: prisma / flyway / alembic (프로젝트별)
## 안전 규칙 (반드시 준수)
1. 프로덕션 마이그레이션 전 스테이징 검증 필수
2. 롤백 스크립트 함께 작성
3. 데이터 손실 가능 변경은 단계적 마이그레이션
## 프로세스
1. 변경사항 분석 (스키마 diff)
2. 마이그레이션 파일 생성
3. 롤백 파일 생성
4. 테스트 실행
5. PR 생성 (마이그레이션 + 롤백 포함)
