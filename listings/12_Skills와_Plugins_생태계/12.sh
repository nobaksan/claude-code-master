# PR Auto Review
## 전제 조건
github MCP 서버가 연결되어 있거나 gh CLI가 설치되어 있어야 한다.
## 리뷰 체크리스트
### 보안
- [ ] 하드코딩된 시크릿 없음
- [ ] SQL 인젝션 취약점 없음
- [ ] XSS 취약점 없음
### 코드 품질
- [ ] 함수 길이 50줄 이하
- [ ] 중복 코드 없음
- [ ] 적절한 에러 핸들링
### 성능
- [ ] N+1 쿼리 패턴 없음
- [ ] 불필요한 리렌더링 없음
- [ ] 메모리 누수 가능성 없음
## 워크플로
1. MCP 또는 gh pr diff로 PR diff 가져오기
2. 체크리스트 기반 분석
3. 라인별 코멘트 생성
4. 전체 요약 작성
