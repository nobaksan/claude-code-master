# MyProject

## 빠른 시작
- 설치 및 실행: `npm install && npm run dev`
- 테스트 확인: `npm test`

## 문서 위치
| 주제                  | 파일 경로               |
| :---                  | :---                    |
| 프로젝트 빌드 및 배포 | `docs/building.md`      |
| 테스트 전략 및 가이드  | `docs/testing.md`       |
| 상세 코드 컨벤션      | `docs/conventions.md`   |
| API 설계 사양          | `docs/api-design.md`    |

현재 수행하려는 작업에 해당하는 상세 문서를 먼저 읽고 작업을 시작한다.
