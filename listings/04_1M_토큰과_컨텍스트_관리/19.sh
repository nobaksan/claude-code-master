# In CLAUDE.md
## 컨텍스트 관리 (Context Management)
진행 상황을 문서화하도록 요청할 때는 다음 템플릿을 사용한다:
### PROGRESS.md 템플릿
- 목표 (Goal): [현재 목표]
- 완료된 작업 (Done): [완료된 작업 목록]
- 진행 중인 작업 (In Progress): [현재 작업 + 정확한 중단 위치]
- 중요 결정사항 (Decisions): [중요한 결정 사항과 그 이유]
- 다음 단계 (Next): [다음에 해야 할 작업 순서]
- 주의사항 (Warnings): [주의해야 할 사항 또는 함정]
