# 작업 인수인계 문서 생성
현재 진행 중인 작업의 상태와 Git Diff 내역을 분석하여 다음 형식으로 문서화한다:
현재 상태
- 진행 중인 작업:
- 완료된 항목:
- 미완료 항목:
발견된 문제점
- 해결됨:
- 미해결 (다음 근무자 처리 필요):
중요 컨텍스트
- 이유 있는 의사결정 기록 (왜 이 아키텍처나 라이브러리를 선택했는지):
- 관련 이슈/PR 링크:
다음 작업 우선순위
1. (긴급)
2. (중요)
3. (여유 있을 때)
작성된 내용은 docs/handoffs/YYYY-MM-DD-[작업자명].md 파일로 자동 저장한다.
