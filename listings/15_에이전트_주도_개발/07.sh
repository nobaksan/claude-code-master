# PR 리뷰 및 개선
사용법: /review [PR 번호 또는 'all']
리뷰 체크리스트
시니어 엔지니어의 관점에서 다음 항목들을 면밀하게 검토한다.
1. 코드 품질
- [ ] 명확한 변수/함수 명명 (의도가 드러나는가?)
- [ ] 적절한 에러 핸들링 (에러를 조용히 무시하고 있지 않은가?)
- [ ] 불필요한 코드(Dead code) 및 콘솔 로그 제거
- [ ] 일관된 코드 스타일
2. 테스트
- [ ] 충분한 테스트 커버리지 확보
- [ ] 에지 케이스(경계값, Null 등) 테스트 포함 여부
- [ ] 테스트 코드 자체의 가독성
3. 문서
- [ ] 복잡한 비즈니스 로직에 필요한 주석 추가
- [ ] README 업데이트 (API 변경 등 필요시)
- [ ] CHANGELOG 항목 추가
4. 보안
- [ ] 하드코딩된 시크릿 키나 민감 정보 노출 없음
- [ ] 사용자 입력 검증 로직 존재
- [ ] SQL 인젝션, XSS 등 알려진 취약점 방어
출력 및 조치
- 발견된 문제점들을 목록화하여 설명한다.
- 각 문제점에 대한 구체적인 개선 코드 스니펫을 제안한다.
- 단순한 오타, 린트 에러 등 자동 수정 가능한 항목은 사용자 동의 없이 직접 파일을 수정한다.
