# /setup-dev 명령어
Claude Code를 사용해 다음을 순차적으로 자동 설정한다:
1. 패키지 의존성 설치 (npm install 또는 pnpm install)
2. 환경 변수 파일 생성 (.env.example 템플릿을 복사하여 .env.local 생성)
3. 데이터베이스 초기화 (pnpm db:migrate && pnpm db:seed 실행)
4. 로컬 서버 실행 확인 (포트 충돌 시 빈 포트 탐색 후 안내)
5. 기본 테스트 실행 확인 (단위 테스트 통과 여부 체크)
진행 중 에러가 발생하면 스스로 에러 로그를 분석하여 수정하고,
모든 과정이 완료된 후 최종 체크리스트를 터미널에 출력한다.
