# PR 설명 자동 생성
현재 브랜치의 변경사항(git diff)을 분석하여 GitHub PR 설명을 작성한다:
변경 요약
[한 줄로 무엇을 왜 변경했는지 핵심만 요약]
변경 내용
- [구체적인 로직 변경 사항 1]
- [구체적인 로직 변경 사항 2]
테스트 방법
[리뷰어가 로컬에서 이 PR을 체크아웃받아 테스트해 볼 수 있는 구체적인 실행 명령어 및 방법]
스크린샷 (UI 변경이 있는 경우)
[before/after 스크린샷 첨부 위치 프롬프트]
체크리스트
- [ ] 테스트 작성/업데이트 완료
- [ ] 문서 업데이트 (필요시)
- [ ] Breaking change 없음 (또는 마이그레이션 가이드 첨부)
Closes #[이관된 이슈번호]
