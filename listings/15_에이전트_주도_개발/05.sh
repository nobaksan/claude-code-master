# GitHub Issue 생성
사용법: /issues [버그 설명 또는 기능 요청]
프로세스
이 프로세스를 순서대로 따른다.
1. 문제 분석
- 제공된 설명 또는 최근 터미널의 에러 로그 분석
- 관련 코드 영역 식별 및 재현 단계 도출
2. 컨텍스트 수집
- 관련 코드 파일 검토 (cat 또는 grep 활용)
- 기존 테스트 케이스 확인
- 의존성 및 영향 범위 파악
3. 이슈 생성
- 명확한 제목 작성
- 재현 단계 포함
- 예상 원인 및 해결 방향 제시
- 적절한 라벨 부착 (bug, enhancement 등)
출력 형식
아래의 마크다운 템플릿을 엄격히 지켜서 출력한다.
[이슈 제목: 명확하고 구체적인 제목]
재현 단계
1. ...
2. ...
예상 동작
[기대하는 결과]
실제 동작
[현재 발생하는 문제 및 스택 트레이스]
분석 및 해결 방향
[원인 추정 및 해결을 위한 아키텍처 접근법]
관련 파일
- file1.ts
- file2.ts
