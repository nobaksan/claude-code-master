# CI 실패 자동 수정
사용법: /fix-ci [PR 번호]
프로세스
1. 로그 수집 (도구 사용)
- gh pr checks $ARGUMENTS --json name,status,conclusion,link 를 실행하여 실패한 Job 확인
- gh run view [run-id] --log-failed 를 실행하여 구체적인 에러 로그 추출
2. 실패 원인 분석
- 테스트 실패: 어떤 테스트 케이스가 어떤 예상/실제 값 불일치로 실패했는지
- 린트/포맷 에러: 어떤 규칙(Rule)을 위반했는지
- 빌드/타입 에러: 타입스크립트 인터페이스 불일치, 의존성 패키지 문제 등 파악
- 인프라/타임아웃 에러: 무한 루프, 느린 DB 쿼리, 네트워크 타임아웃 등
3. 자동 수정 및 검증
- 수정 가능한 논리적, 문법적 에러는 직접 소스 코드를 수정
- 수정 후 로컬에서 해당 테스트만 단독으로 다시 실행하여 검증 (npm test -- [파일명])
- 통과 시 새 커밋 작성 후 원격 저장소에 푸시
4. 수정 불가능한 경우 (Escalation)
- API 키 누락, 외부 서비스 장애, 대규모 아키텍처 변경이 필요한 경우 직접 수정하지 말 것
- 문제점을 상세히 설명하고 가능한 해결 방향을 개발자에게 제시
