# Issue 구현 및 PR 생성
사용법: /work [이슈 번호]
워크플로
1. 이슈 분석 ($ARGUMENTS 파싱)
- GitHub CLI(gh issue view $ARGUMENTS)를 통해 이슈 내용 확인
- 요구사항 및 수용 기준(Acceptance Criteria) 파악
2. 구현 계획
- 변경이 필요한 파일 목록 작성
- 구현 순서 결정 및 잠재적 영향 범위 분석
3. 테스트 우선 개발 (TDD)
- 실패하는 테스트 먼저 작성
- 본 구현 진행
- 테스트 통과 확인
4. 품질 검증
- 린트(Lint) 및 타입 체크 실행
- 기존 테스트 전체 실행하여 회귀(Regression) 에러 확인
- 에지 케이스 처리 확인
5. PR 생성
- 의미 있는 커밋 메시지 작성
- PR 설명에 Closes #$ARGUMENTS 링크 포함
- 변경사항 요약
주의사항 (Guardrails)
- 테스트를 억지로 통과시키기 위해 기존 조건문이나 단언(Assertion)을 주석 처리하거나 비활성화하지 않는다.
- 과도하거나 무의미한 테스트(Trivial tests) 작성은 자제한다.
- 요청된 이슈의 범위만 구현한다 (오버엔지니어링 금지).
